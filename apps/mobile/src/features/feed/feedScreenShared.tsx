export function errorMessage(error: unknown) { return error instanceof Error ? error.message : "Не удалось загрузить «Моменты»."; }

export function useFeedStatus() {
  const id = useAuthStore(state => state.user?.id);
  return useQuery({
    queryKey: ["feed-status", id],
    queryFn: () => feedApi.status(),
    enabled: !!id,
    retry: 1,
    staleTime: 30_000,
  });
}

export function Muted({ children }: { children: React.ReactNode }) { return <Text style={s.muted}>{children}</Text>; }

export function Status({ status, retry }: { status: ReturnType<typeof useFeedStatus>; retry?: () => void }) {
  if (status.isPending) return <Loading variant="inline" />;
  if (status.isError) return <View style={s.card}><Text style={s.error}>{errorMessage(status.error)}</Text><Button label="Повторить" onPress={() => void (retry?.() ?? status.refetch())} /></View>;
  return <View style={s.card}><Muted>Раздел «Моменты» пока недоступен.</Muted></View>;
}

