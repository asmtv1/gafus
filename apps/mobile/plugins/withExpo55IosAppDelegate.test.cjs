const assert = require('node:assert/strict');
const { test } = require('node:test');
const { patchAppDelegate } = require('./withExpo55IosAppDelegate');
const legacy = `import Expo\nimport OKTracer\nimport React\n\n@UIApplicationMain\npublic class AppDelegate: ExpoAppDelegate {\n  // @generated by withAppTracerNative: service\n  private var appTracerService: TracerServiceProtocol?\n  bindReactNativeFactory(factory)\n  public override func application() {}\n}\n`;

test('migrates Expo 54 Swift entry point and import access to Expo 55', () => {
  const actual = patchAppDelegate(legacy);
  assert.match(actual, /^internal import Expo$/m);
  assert.match(actual, /^@main$/m);
  assert.match(actual, /^class AppDelegate: ExpoAppDelegate/m);
  assert.doesNotMatch(actual, /@UIApplicationMain|public class AppDelegate|bindReactNativeFactory/);
  assert.match(actual, /import OKTracer/);
  assert.match(actual, /appTracerService/);
});
test('accepts an already migrated app delegate without changes', () => {
  const converted = patchAppDelegate(legacy);
  assert.equal(patchAppDelegate(converted), converted);
});
test('rejects unknown iOS AppDelegate layout rather than silently modifying', () => {
  assert.throws(() => patchAppDelegate('import Expo\nclass OtherApp {}'), /Unexpected/);
});
