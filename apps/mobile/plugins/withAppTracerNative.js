const {
  withAppBuildGradle,
  withAppDelegate,
  withInfoPlist,
  withMainApplication,
  withPodfile,
  withSettingsGradle,
  withXcodeProject,
} = require("expo/config-plugins");

const TRACER_VERSION = "1.4.0";
const IOS_TOKEN_INFO_PLIST_KEY = "GAFUS_APPTRACER_APP_TOKEN";
const IOS_DSYM_PHASE_NAME = "[AppTracer] Upload dSYM";

function requireBuildToken(name) {
  const value = process.env[name]?.trim();
  if (value) return value;

  if (process.env.APP_ENV === "production") {
    throw new Error(`${name} is required for a production native build`);
  }

  return null;
}

function escapeGroovyString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function escapeShellSingleQuoted(value) {
  return value.replace(/'/g, `'"'"'`);
}

function withAndroidTracer(config, { appToken, pluginToken }) {
  config = withSettingsGradle(config, (mod) => {
    if (!appToken || !pluginToken) return mod;

    const marker = "// @generated by withAppTracerNative: plugin repositories";
    if (!mod.modResults.contents.includes(marker)) {
      mod.modResults.contents = mod.modResults.contents.replace(
        "pluginManagement {",
        `pluginManagement {\n  ${marker}\n  repositories {\n    google()\n    mavenCentral()\n    gradlePluginPortal()\n  }`,
      );
    }
    return mod;
  });

  config = withAppBuildGradle(config, (mod) => {
    if (!appToken || !pluginToken) return mod;

    let source = mod.modResults.contents;
    const pluginMarker = "// @generated by withAppTracerNative: Gradle plugin";
    if (!source.includes(pluginMarker)) {
      source = `${pluginMarker}\nplugins {\n    id "ru.ok.tracer" version "${TRACER_VERSION}"\n}\n\n${source}`;
    }

    const buildFeaturesMarker = "// @generated by withAppTracerNative: resValues";
    if (!source.includes(buildFeaturesMarker)) {
      source = source.replace(
        /android\s*\{\s*\n/,
        `android {\n    ${buildFeaturesMarker}\n    buildFeatures {\n        resValues true\n    }\n`,
      );
    }

    const dependencyMarker = "// @generated by withAppTracerNative: runtime";
    if (!source.includes(dependencyMarker)) {
      source = source.replace(
        /dependencies\s*\{\s*\n/,
        `dependencies {\n    ${dependencyMarker}\n    implementation platform("ru.ok.tracer:tracer-platform:${TRACER_VERSION}")\n    implementation "ru.ok.tracer:tracer-crash-report"\n    implementation "ru.ok.tracer:tracer-crash-report-native"\n`,
      );
    }

    const configurationMarker = "// @generated by withAppTracerNative: build configuration";
    if (!source.includes(configurationMarker)) {
      source += `\n${configurationMarker}\ntracer {\n    create("defaultConfig") {\n        pluginToken = "${escapeGroovyString(pluginToken)}"\n        appToken = "${escapeGroovyString(appToken)}"\n        uploadMapping = true\n        uploadNativeSymbols = true\n    }\n}\n`;
    }

    mod.modResults.contents = source;
    return mod;
  });

  return withMainApplication(config, (mod) => {
    if (!appToken || !pluginToken) return mod;

    let source = mod.modResults.contents;
    const importMarker = "// @generated by withAppTracerNative: imports";
    if (!source.includes(importMarker)) {
      source = source.replace(
        /package\s+[^\n]+\n/,
        (match) =>
          `${match}\n${importMarker}\nimport ru.ok.tracer.CoreTracerConfiguration\nimport ru.ok.tracer.HasTracerConfiguration\nimport ru.ok.tracer.TracerConfiguration\nimport ru.ok.tracer.crash.report.CrashFreeConfiguration\nimport ru.ok.tracer.crash.report.CrashReportConfiguration\n`,
      );
    }

    if (!source.includes("HasTracerConfiguration {")) {
      source = source.replace(
        /class MainApplication\s*:\s*Application\(\),\s*ReactApplication\s*\{/,
        "class MainApplication : Application(), ReactApplication, HasTracerConfiguration {",
      );
    }

    const configurationMarker = "// @generated by withAppTracerNative: configuration";
    if (!source.includes(configurationMarker)) {
      source = source.replace(
        /class MainApplication[^\n]*\{\s*\n/,
        (match) =>
          `${match}  ${configurationMarker}\n  override val tracerConfiguration: List<TracerConfiguration>\n    get() = listOf(\n      CoreTracerConfiguration.build { setDebugUpload(BuildConfig.DEBUG) },\n      CrashReportConfiguration.build {\n        setEnabled(true)\n        setNativeEnabled(true)\n        setSendAnr(true)\n      },\n      CrashFreeConfiguration.build { setEnabled(true) },\n    )\n\n`,
      );
    }

    mod.modResults.contents = source;
    return mod;
  });
}

function withIosTracer(config, { appToken, pluginToken }) {
  config = withInfoPlist(config, (mod) => {
    if (appToken) mod.modResults[IOS_TOKEN_INFO_PLIST_KEY] = appToken;
    return mod;
  });

  config = withPodfile(config, (mod) => {
    if (!appToken) return mod;

    let source = mod.modResults.contents;
    const sourceLine = "source 'https://github.com/odnoklassniki/tracer-ios.git'";
    if (!source.includes(sourceLine)) {
      source = `${sourceLine}\n${source}`;
    }

    const podLine = `  pod 'OKTracer', '${TRACER_VERSION}'`;
    if (!source.includes("pod 'OKTracer'")) {
      source = source.replace(
        /target\s+['"][^'"]+['"]\s+do\s*\n/,
        (match) => `${match}${podLine}\n`,
      );
    }

    mod.modResults.contents = source;
    return mod;
  });

  config = withAppDelegate(config, (mod) => {
    if (!appToken) return mod;
    if (mod.modResults.language !== "swift") {
      throw new Error("withAppTracerNative supports only a Swift iOS AppDelegate");
    }

    let source = mod.modResults.contents;
    if (!source.includes("import OKTracer")) {
      source = source.replace("import Expo\n", "import Expo\nimport OKTracer\n");
    }

    const propertyMarker = "// @generated by withAppTracerNative: service";
    if (!source.includes(propertyMarker)) {
      source = source.replace(
        /public class AppDelegate:\s*ExpoAppDelegate\s*\{\s*\n/,
        (match) =>
          `${match}  ${propertyMarker}\n  private var appTracerService: TracerServiceProtocol?\n`,
      );
    }

    const startMarker = "// @generated by withAppTracerNative: start";
    if (!source.includes(startMarker)) {
      source = source.replace(
        /(didFinishLaunchingWithOptions launchOptions:[^\n]*\n\s*\) -> Bool \{\s*\n)/,
        (match) =>
          `${match}    ${startMarker}\n    if let token = Bundle.main.object(forInfoDictionaryKey: "${IOS_TOKEN_INFO_PLIST_KEY}") as? String, !token.isEmpty {\n      appTracerService = TracerFactory.tracerServiceForCrashReporting(EndpointConfiguration(token: token))\n      appTracerService?.start()\n    }\n\n`,
      );
    }

    mod.modResults.contents = source;
    return mod;
  });

  return withXcodeProject(config, (mod) => {
    if (!pluginToken) return mod;

    const project = mod.modResults;
    const phases = project.hash.project.objects.PBXShellScriptBuildPhase ?? {};
    const alreadyAdded = Object.values(phases).some(
      (phase) =>
        (typeof phase === "string" && phase.includes(IOS_DSYM_PHASE_NAME)) ||
        (typeof phase === "object" && phase?.name?.includes(IOS_DSYM_PHASE_NAME)),
    );
    if (alreadyAdded) return mod;

    const token = escapeShellSingleQuoted(pluginToken);
    const shellScript = `set -euo pipefail\n\nif [ \"$ACTION\" != \"install\" ] || [ \"$CONFIGURATION\" != \"Release\" ]; then\n  exit 0\nfi\n\nDSYM_PATH=\"$DWARF_DSYM_FOLDER_PATH/$DWARF_DSYM_FILE_NAME\"\nif [ ! -d \"$DSYM_PATH\" ]; then\n  echo \"AppTracer: dSYM not found at $DSYM_PATH\"\n  exit 0\nfi\n\nARCHIVE_PATH=\"$DERIVED_FILE_DIR/apptracer-${"$"}{CURRENT_PROJECT_VERSION}.dSYM.zip\"\n/usr/bin/ditto -c -k --keepParent \"$DSYM_PATH\" \"$ARCHIVE_PATH\"\n/usr/bin/curl --fail --silent --show-error --retry 3 \\\n  -F \"file=@$ARCHIVE_PATH\" \\\n  \"https://plugin-api.apptracer.ru/api/symbol/upload?symbolToken=${token}&versionName=${"$"}{MARKETING_VERSION}&versionCode=${"$"}{CURRENT_PROJECT_VERSION}\"\n`;

    const target = project.getFirstTarget().uuid;
    project.addBuildPhase([], "PBXShellScriptBuildPhase", IOS_DSYM_PHASE_NAME, target, {
      shellPath: "/bin/bash",
      shellScript: shellScript.replace(/\n/g, "\\n"),
      inputPaths: ['"$(DWARF_DSYM_FOLDER_PATH)/$(DWARF_DSYM_FILE_NAME)"'],
    });
    return mod;
  });
}

module.exports = function withAppTracerNative(config) {
  const androidAppToken = requireBuildToken("EXPO_PUBLIC_TRACER_APP_TOKEN_ANDROID");
  const androidPluginToken = requireBuildToken("TRACER_PLUGIN_TOKEN_ANDROID");
  const iosAppToken = requireBuildToken("EXPO_PUBLIC_TRACER_APP_TOKEN_IOS");
  const iosPluginToken = requireBuildToken("TRACER_PLUGIN_TOKEN_IOS");

  config = withAndroidTracer(config, {
    appToken: androidAppToken,
    pluginToken: androidPluginToken,
  });
  return withIosTracer(config, {
    appToken: iosAppToken,
    pluginToken: iosPluginToken,
  });
};
