const assert = require('node:assert/strict');
const { test } = require('node:test');
const { patchMainApplication } = require('./withExpo55ReactHost');
const legacy = `package ru.gafus.app\nimport com.facebook.react.ReactNativeHost\nimport com.facebook.react.ReactHost\nimport com.facebook.react.defaults.DefaultReactNativeHost\nimport expo.modules.ReactNativeHostWrapper\nclass MainApplication : Application(), ReactApplication, HasTracerConfiguration {\n  // @generated by withAppTracerNative: configuration\n  override val tracerConfiguration: List<TracerConfiguration>\n    get() = listOf()\n  override val reactNativeHost: ReactNativeHost = ReactNativeHostWrapper(\n      this,\n      object : DefaultReactNativeHost(this) {\n        override fun getPackages(): List<ReactPackage> =\n            PackageList(this).packages\n      }\n  )\n  override val reactHost: ReactHost\n    get() = ReactNativeHostWrapper.createReactHost(applicationContext, reactNativeHost)\n  override fun onCreate() {\n    registerActivityLifecycleCallbacks(lifecycleCallbacks)\n  }\n  private val lifecycleCallbacks = object : ActivityLifecycleCallbacks {}\n}\n`;

test('migrates removed Expo 54 wrapper to Expo 55 ReactHostFactory', () => {
  const actual = patchMainApplication(legacy);
  assert.match(actual, /ExpoReactHostFactory\.getDefaultReactHost\(/);
  assert.match(actual, /packageList =/);
  assert.doesNotMatch(actual, /ReactNativeHostWrapper|DefaultReactNativeHost/);
  assert.match(actual, /registerActivityLifecycleCallbacks\(lifecycleCallbacks\)/);
  assert.match(actual, /@generated by withAppTracerNative: configuration/);
});

test('idempotent for new Expo host implementation', () => {
  const actual = patchMainApplication(legacy);
  assert.equal(patchMainApplication(actual), actual);
});

test('rejects unknown outdated host implementation', () => {
  assert.throws(() => patchMainApplication('class MainApplication : Application() {}'), /Unexpected Expo 55/);
});
