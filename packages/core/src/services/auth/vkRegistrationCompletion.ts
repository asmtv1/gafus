import crypto from "node:crypto";

import { ConsentLogStatus, Prisma, prisma } from "@gafus/prisma";

import { attributePartnerReferralIfCurrentPartnerInTransaction } from "../appSubscription/partnerService";
import { createCompletedConsentLogsInTransaction } from "../consent/consentService";
import type { CreateConsentLogsParams } from "../consent/types";
import {
  RegistrationContractError,
  hashRegistrationOpaqueValue,
  issueVkLoginGrantInTransaction,
  resolveRegistrationPromoCodeInTransaction,
  saveRegistrationPromoCodeInTransaction,
} from "./registrationContracts";

export type VkCompletionTransport = "WEB" | "MOBILE";

export interface CompleteVkRegistrationParams {
  contextToken: string;
  state: string;
  /** An edited promo is allowed until completion; otherwise use the saved selection. */
  promoCode?: string | null;
  consent: CreateConsentLogsParams;
  transport: VkCompletionTransport;
  /** Generated by the web transport, never persisted in plaintext. */
  loginGrantToken?: string;
}

export interface CompletedVkRegistration {
  user: { id: string; username: string; role: string; needsPhone: boolean };
  /** WEB only. This is a LOGIN grant, never a registration/consent token. */
  loginGrantToken?: string;
  replayed: boolean;
}

function normalizeOptionalPromo(raw: string | null | undefined): string | null {
  if (raw == null || raw.trim() === "") return null;
  return raw.trim().toUpperCase();
}

function completionFingerprint(params: CompleteVkRegistrationParams, promo: string | null): string {
  const consent = params.consent;
  return hashRegistrationOpaqueValue(JSON.stringify({
    promo,
    consent: {
      tempSessionId: consent.tempSessionId,
      consentPayload: consent.consentPayload,
      formData: consent.formData,
      ipAddress: consent.ipAddress ?? null,
      userAgent: consent.userAgent ?? null,
      consentVersions: consent.consentVersions ?? {},
      defaultVersion: consent.defaultVersion,
    },
    transport: params.transport,
  }));
}

function assertAcceptedConsent(consent: CreateConsentLogsParams): void {
  if (!consent.consentPayload.acceptPersonalData || !consent.consentPayload.acceptPrivacyPolicy || !consent.consentPayload.acceptDataDistribution) {
    throw new RegistrationContractError("VK_COMPLETION_ATTEMPT_CONFLICT");
  }
}

/**
 * Completes a previously claimed REGISTER context. OAuth/network work is
 * intentionally absent: callers exchange the code and claim the context first.
 */
export async function completeVkRegistration(params: CompleteVkRegistrationParams): Promise<CompletedVkRegistration> {
  if (params.transport === "WEB" && !params.loginGrantToken) {
    throw new RegistrationContractError("VK_LOGIN_GRANT_INVALID");
  }
  if (params.transport === "MOBILE" && params.loginGrantToken) {
    throw new RegistrationContractError("VK_LOGIN_GRANT_INVALID");
  }
  assertAcceptedConsent(params.consent);

  return prisma.$transaction(async (tx) => {
    // Serialize completion/replay and grant reissue by opaque context, while
    // leaving external OAuth calls outside this transaction.
    await tx.$executeRaw(
      Prisma.sql`SELECT pg_advisory_xact_lock(hashtextextended(${hashRegistrationOpaqueValue(params.contextToken)}, 0))`,
    );
    const now = new Date();
    const context = await tx.vkRegistrationContext.findUnique({
      where: { contextTokenHash: hashRegistrationOpaqueValue(params.contextToken) },
      include: {
        user: { select: { id: true, username: true, role: true, phone: true, registrationPending: true } },
        selectedPromoCode: { select: { code: true } },
        resultUser: { select: { id: true, username: true, role: true, phone: true } },
      },
    });
    if (!context || context.stateHash !== hashRegistrationOpaqueValue(params.state)) {
      throw new RegistrationContractError("VK_CONTEXT_INVALID");
    }
    if (context.purpose !== "REGISTER") throw new RegistrationContractError("VK_CONTEXT_PURPOSE_INVALID");
    // The deadline does not extend after success; expiry wins even for replay.
    if (context.expiresAt <= now) throw new RegistrationContractError("VK_CONTEXT_EXPIRED");

    const savedPromo = context.selectedPromoCodeValue ?? context.selectedPromoCode?.code ?? null;
    const selectedPromo = normalizeOptionalPromo(params.promoCode) ?? savedPromo;
    const fingerprint = completionFingerprint(params, selectedPromo);

    if (context.completedAt) {
      if (!context.resultUser || context.completionFingerprint !== fingerprint) {
        throw new RegistrationContractError("VK_COMPLETION_ATTEMPT_CONFLICT");
      }
      let loginGrantToken: string | undefined;
      if (params.transport === "WEB") {
        // The context lock makes "invalidate then reissue" deterministic. A
        // lost response can retry, but the previous unconsumed grant is dead.
        await tx.vkLoginGrant.updateMany({
          where: { registrationContextId: context.id, purpose: "LOGIN", consumedAt: null },
          data: { consumedAt: now },
        });
        await issueVkLoginGrantInTransaction(tx, {
          token: params.loginGrantToken!, userId: context.resultUser.id,
          purpose: "LOGIN", registrationContextId: context.id, expiresAt: context.expiresAt,
        });
        loginGrantToken = params.loginGrantToken;
      }
      return {
        user: { id: context.resultUser.id, username: context.resultUser.username, role: context.resultUser.role, needsPhone: context.resultUser.phone?.startsWith("vk_") ?? false },
        ...(loginGrantToken ? { loginGrantToken } : {}), replayed: true,
      };
    }

    if (!context.user || !context.user.registrationPending) {
      throw new RegistrationContractError("VK_COMPLETION_ATTEMPT_CONFLICT");
    }

    // Validate the current row inside the completion transaction. A saved promo
    // may have been edited, archived or deleted between OAuth and consent.
    const resolvedPromo = selectedPromo
      ? await resolveRegistrationPromoCodeInTransaction(tx, selectedPromo)
      : null;
    if (resolvedPromo) {
      await saveRegistrationPromoCodeInTransaction(tx, { userId: context.user.id, rawCode: selectedPromo });
      await attributePartnerReferralIfCurrentPartnerInTransaction(tx, context.user.id, resolvedPromo.normalizedCode);
    }
    await createCompletedConsentLogsInTransaction(tx, {
      ...params.consent,
      userId: context.user.id,
    }, ConsentLogStatus.COMPLETED);
    const completedUser = await tx.user.updateMany({
      where: { id: context.user.id, registrationPending: true },
      data: { registrationPending: false },
    });
    if (completedUser.count !== 1) throw new RegistrationContractError("VK_COMPLETION_ATTEMPT_CONFLICT");

    await tx.vkRegistrationContext.update({
      where: { id: context.id },
      data: { resultUserId: context.user.id, completionFingerprint: fingerprint, completedAt: now },
    });
    let loginGrantToken: string | undefined;
    if (params.transport === "WEB") {
      await issueVkLoginGrantInTransaction(tx, {
        token: params.loginGrantToken!, userId: context.user.id,
        purpose: "LOGIN", registrationContextId: context.id, expiresAt: context.expiresAt,
      });
      loginGrantToken = params.loginGrantToken;
    }
    return {
      user: { id: context.user.id, username: context.user.username, role: context.user.role, needsPhone: context.user.phone?.startsWith("vk_") ?? false },
      ...(loginGrantToken ? { loginGrantToken } : {}), replayed: false,
    };
  });
}

/** Safe utility for a transport that needs a new opaque grant before retrying. */
export function createVkLoginGrantToken(): string {
  return crypto.randomBytes(32).toString("base64url");
}
