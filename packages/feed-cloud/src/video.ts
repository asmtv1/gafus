/** Pure input validation and deterministic ffmpeg arguments for private feed VOD. */
export const FEED_VIDEO_MAX_BYTES = 200 * 1024 * 1024;
export const FEED_VIDEO_MAX_SECONDS = 60;
export const FEED_SEGMENT_MAX_BYTES = 1_750_000;

export interface ProbeStream {
  codec_type?: string;
  codec_name?: string;
  width?: number;
  height?: number;
  duration?: string;
  avg_frame_rate?: string;
  color_transfer?: string;
  side_data_list?: Array<{ rotation?: number }>;
}
export interface ProbeResult {
  format?: { duration?: string; size?: string };
  streams?: ProbeStream[];
}
export interface VideoInfo {
  durationSeconds: number;
  width: number;
  height: number;
  rotated: boolean;
  hdr: boolean;
  hasAudio: boolean;
}
export class FeedVideoError extends Error {
  constructor(public readonly code: string) {
    super(code);
    this.name = "FeedVideoError";
  }
}
/** Inspects authoritative probed media rather than client-supplied duration/size. */
export function validateVideoProbe(probe: ProbeResult, sourceBytes: number): VideoInfo {
  if (!Number.isSafeInteger(sourceBytes) || sourceBytes <= 0 || sourceBytes > FEED_VIDEO_MAX_BYTES) {
    throw new FeedVideoError("VIDEO_SIZE");
  }
  const video = probe.streams?.find(stream => stream.codec_type === "video");
  if (!video || !Number.isSafeInteger(video.width) || !Number.isSafeInteger(video.height) ||
    !video.width || !video.height || video.width <= 0 || video.height <= 0) {
    throw new FeedVideoError("VIDEO_STREAM_MISSING");
  }
  const durations = [probe.format?.duration, video.duration]
    .filter((value): value is string => typeof value === "string")
    .map(Number)
    .filter(value => Number.isFinite(value) && value > 0);
  if (!durations.length) throw new FeedVideoError("VIDEO_DURATION_UNKNOWN");
  // The longest declared timeline is authoritative; never silently trim a >60s input.
  const durationSeconds = Math.max(...durations);
  if (durationSeconds > FEED_VIDEO_MAX_SECONDS) throw new FeedVideoError("VIDEO_TOO_LONG");
  const angle = video.side_data_list?.find(item => typeof item.rotation === "number")?.rotation ?? 0;
  const rotated = Math.abs(angle) % 180 === 90;
  const width = rotated ? video.height : video.width;
  const height = rotated ? video.width : video.height;
  const hdr = ["smpte2084", "arib-std-b67"].includes(video.color_transfer ?? "");
  return { durationSeconds, width, height, rotated, hdr,
    hasAudio: !!probe.streams?.some(stream => stream.codec_type === "audio") };
}
/** H.264/AAC HLS with one conservative rendition, no upscaling and approximately 2s segments. */
export function feedFfmpegArguments(input: string, outputDir: string, info: VideoInfo): string[] {
  if (!input || !outputDir) throw new FeedVideoError("VIDEO_PATH");
  const portrait = info.height > info.width;
  const width = portrait ? 720 : 1280;
  const height = portrait ? 1280 : 720;
  const scale = `scale=w='min(${width},iw)':h='min(${height},ih)':force_original_aspect_ratio=decrease:force_divisible_by=2:flags=lanczos`;
  const toneMap = info.hdr
    ? "zscale=t=linear:npl=100,format=gbrpf32le,zscale=p=bt709,tonemap=tonemap=hable:desat=0,zscale=t=bt709:m=bt709:r=tv,"
    : "";
  return [
    "-hide_banner", "-nostdin", "-loglevel", "warning", "-y",
    "-i", input,
    "-map", "0:v:0", "-map", "0:a:0?",
    "-vf", `${toneMap}${scale},format=yuv420p`,
    "-c:v", "libx264", "-preset", "veryfast", "-profile:v", "main", "-level", "3.1",
    "-fpsmax", "30", "-force_key_frames", "expr:gte(t,n_forced*2)", "-b:v", "1400k", "-maxrate", "1800k", "-bufsize", "3600k",
    "-g", "60", "-keyint_min", "60", "-sc_threshold", "0",
    "-c:a", "aac", "-b:a", "96k", "-ac", "2",
    "-max_muxing_queue_size", "1024",
    "-hls_time", "2", "-hls_list_size", "0", "-hls_playlist_type", "vod",
    "-hls_flags", "independent_segments",
    "-hls_segment_filename", `${outputDir}/segment-%03d.ts`,
    "-f", "hls", `${outputDir}/playlist.m3u8`,
  ];
}
export function feedPosterArguments(input: string, outputPath: string): string[] {
  return ["-hide_banner", "-nostdin", "-loglevel", "warning", "-y", "-i", input,
    "-map", "0:v:0", "-frames:v", "1", "-vf",
    "scale=w='min(720,iw)':h='min(720,ih)':force_original_aspect_ratio=decrease:force_divisible_by=2,format=yuv420p",
    "-an", "-c:v", "libwebp", "-quality", "82", outputPath];
}
/** Fail closed on any playlist reference not generated by the processor. */
export function parseFeedHlsPlaylist(playlist: string): string[] {
  if (!playlist.startsWith("#EXTM3U") || !playlist.includes("#EXT-X-ENDLIST")) {
    throw new FeedVideoError("VIDEO_PLAYLIST");
  }
  const names = playlist.split(/\r?\n/).map(line => line.trim()).filter(line => line && !line.startsWith("#"));
  if (!names.length || names.length > 60 ||
      names.some(name => !/^segment-[0-9]{3,5}\.ts$/.test(name)) ||
      new Set(names).size !== names.length) {
    throw new FeedVideoError("VIDEO_SEGMENT_PATH");
  }
  return names;
}
export function validateSegmentSizes(segments: readonly { name: string; bytes: number }[]): void {
  if (!segments.length || segments.length > 60 || new Set(segments.map(s => s.name)).size !== segments.length)
    throw new FeedVideoError("VIDEO_SEGMENT_LIST");
  for (const segment of segments) {
    if (!/^segment-[0-9]{3,5}\.ts$/.test(segment.name) ||
        !Number.isSafeInteger(segment.bytes) || segment.bytes <= 0 || segment.bytes > FEED_SEGMENT_MAX_BYTES) {
      throw new FeedVideoError("VIDEO_SEGMENT_SIZE");
    }
  }
}
